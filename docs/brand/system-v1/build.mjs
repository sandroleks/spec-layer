import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import * as esbuild from 'esbuild';
import { buildBrand } from '../../../packages/brand/build.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../../..');
const spec = JSON.parse(await readFile(resolve(here, 'tokens.json'), 'utf8'));
const declarations = values => Object.entries(values).map(([key, value]) => `  --brand-${key}: ${value};`).join('\n');
const css = `/* Generated by build.mjs from tokens.json. Proposal only. */\n:root {\n${declarations(spec.shared)}\n}\n` +
  Object.entries(spec.themes).map(([theme, values]) => `:root[data-theme="${theme}"], body[data-theme="${theme}"] {\n  color-scheme: ${theme};\n${declarations(values)}\n}`).join('\n');
await writeFile(resolve(here, 'tokens.css'), css);

const mapping = {
  'font-family': 'font-ui',
  ...Object.fromEntries(['micro', 'caption', 'support', 'control', 'body', 'section', 'display'].map(k => [`font-size-${k}`, `size-${k}`])),
  ...Object.fromEntries(['regular', 'medium', 'semibold', 'bold'].map(k => [`font-weight-${k}`, `weight-${k}`])),
  ...Object.fromEntries(['xs', 'sm', 'md', 'lg', 'pill'].map(k => [`radius-${k}`, `radius-${k}`])),
  ...Object.fromEntries(['xs', 'sm', 'md', 'lg'].map(k => [`control-${k}`, `control-${k}`])),
  ...Object.fromEntries(['fast', 'standard', 'slow'].map(k => [`motion-${k}`, `motion-${k}`])),
  'color-canvas':'canvas', 'color-chrome':'chrome', 'color-surface':'surface',
  'color-surface-subdued':'subdued', 'color-surface-raised':'raised',
  'color-surface-hover':'hover', 'color-surface-pressed':'pressed',
  'color-surface-selected':'selected', 'color-overlay':'overlay',
  'color-section-header':'surface', 'color-detail-surface':'subdued',
  'color-ai-surface':'subdued', 'color-ai-border':'divider',
  'color-border':'divider', 'color-border-muted':'divider-muted',
  'color-border-strong':'control-border', 'color-border-hover':'control-border',
  'color-text':'text', 'color-text-muted':'muted', 'color-text-quiet':'quiet',
  'color-text-disabled':'disabled', 'color-text-on-accent':'on-action',
  'color-accent':'action', 'color-accent-hover':'action-hover', 'color-accent-pressed':'action-pressed',
  'color-accent-text':'accent-text', 'color-accent-soft':'selected', 'color-accent-border':'action',
  'color-focus':'focus', 'color-ai-badge-text':'muted', 'color-ai-badge-bg':'surface', 'color-ai-badge-border':'divider',
  'color-success':'success', 'color-success-soft':'success-soft', 'color-success-border':'success',
  'color-warning':'warning', 'color-warning-soft':'warning-soft', 'color-warning-border':'warning',
  'color-warning-graphic':'warning-graphic', 'color-danger':'danger', 'color-danger-soft':'danger-soft',
  'color-danger-border':'danger', 'color-source-icon':'muted', 'color-control-thumb':'thumb',
};
const bridge = `/* Candidate mapping only; not imported by the production plugin. */\nbody[data-theme] {\n${Object.entries(mapping).map(([a,b])=>`  --sl-${a}: var(--brand-${b});`).join('\n')}\n}\n`;
await writeFile(resolve(here, 'plugin-tokens.css'), bridge);

const pluginDir = resolve(root, 'packages/plugin');
// The production CSS now imports the shared brand package. Resolve those
// imports before embedding so this dated review remains independently usable.
await buildBrand();
const layers = await esbuild.build({entryPoints:[resolve(pluginDir,'src/ui/design-system/index.css')],bundle:true,write:false});
const stagedLayers = layers.outputFiles[0].text;
const corrections = await readFile(resolve(here, 'plugin-patterns.css'), 'utf8');
const pkg = JSON.parse(await readFile(resolve(pluginDir, 'package.json'), 'utf8'));
const bundled = await esbuild.build({entryPoints:[resolve(pluginDir,'src/ui/harness.ts')], bundle:true, platform:'browser', format:'iife', target:'es2017', minify:true, write:false, define:{__PLUGIN_VERSION__:JSON.stringify(pkg.version)}});
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Spec Layer proposed plugin system</title><style>${stagedLayers}\n${css}\n${bridge}\n${corrections}\nhtml,body{width:100%;height:100%;margin:0;overflow:hidden}</style></head><body data-theme="dark"><script>${bundled.outputFiles[0].text}</script></body></html>`;
await writeFile(resolve(here, 'plugin-preview.html'), html);

function luminance(hex) {
  const rgb = hex.slice(1).match(/../g).map(x=>parseInt(x,16)/255).map(x=>x<=.04045?x/12.92:((x+.055)/1.055)**2.4);
  return rgb[0]*.2126+rgb[1]*.7152+rgb[2]*.0722;
}
const checks = [];
for (const [theme, t] of Object.entries(spec.themes)) {
  function add(fg,bg,min,kind) {
    const a=luminance(t[fg]),b=luminance(t[bg]);
    const ratio=(Math.max(a,b)+.05)/(Math.min(a,b)+.05);
    checks.push({theme,foreground:fg,background:bg,ratio:+ratio.toFixed(3),minimum:min,pass:ratio>=min,kind});
  }
  for(const bg of ['canvas','chrome','surface','subdued','raised','hover','pressed']) {
    for(const fg of ['text','muted','quiet']) add(fg,bg,4.5,'text');
    add('control-border',bg,3,'control boundary');
    add('focus',bg,3,'focus');
  }
  for(const bg of ['action','action-hover','action-pressed']) {
    add('on-action',bg,4.5,'action text');
    add('thumb',bg,3,'switch thumb');
  }
  add('thumb','control-border',3,'off switch thumb');
  add('accent-text','selected',4.5,'selected text');
  add('on-danger','danger-fill',4.5,'danger action');
  for(const key of ['success','warning','danger']) add(key,key+'-soft',4.5,'status text');
  add('warning-graphic','raised',3,'quota graphic');
}
const report = {status: checks.every(c=>c.pass)?'passed':'failed', methodology:'WCAG sRGB relative luminance. Semantic token pairs only; not a full accessibility audit.', checks};
await writeFile(resolve(here,'contrast-report.json'),JSON.stringify(report,null,2)+'\n');
if(report.status==='failed') { console.error(checks.filter(c=>!c.pass)); process.exitCode=1; }
else console.log(`Built proposal and plugin preview. ${checks.length} contrast pairs passed.`);
