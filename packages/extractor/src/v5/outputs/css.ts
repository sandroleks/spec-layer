/**
 * `names` is the permanent assignment from `resolveNames` (a missing path
 * collided and was reported); `alive` is this fixed-point pass's declared
 * paths, which references are checked against. Every non-collided leaf is
 * attempted every pass, so the stable pass reports each omission afresh.
 */
interface Ctx {
  names: Map<string, string>; alive: Set<string>; report: OutputReportEntry[]; path: string; mode?: string;
  /** Whether the path's own Figma scopes state a unitless number (`OPACITY`,
   *  `FONT_WEIGHT`); a DTCG leaf cannot say, and the remedy depends on it. */
  statesNumber: boolean;
}

const REF = /^\{(.+)\}$/;

function hexChannels(hex: string): [number, number, number] {
  const at = (i: number) => parseInt(hex.slice(i, i + 2), 16);
  return [at(1), at(3), at(5)];
}
const quoteFamily = (f: string): string => `"${f.replace(/["\\]/g, '\\$&')}"`;

function report(ctx: Ctx, entry: Omit<OutputReportEntry, 'path' | 'mode'>): void {
  ctx.report.push({ ...entry, path: ctx.path, ...(ctx.mode !== undefined ? { mode: ctx.mode } : {}) });
}

/** One CSS value, or null when omitted and reported. `property` names a style member. */
function cssValue(ctx: Ctx, type: string, value: DtcgJson, property?: string): string | null {
  const member: Record<string, DtcgJson> = property !== undefined ? { property } : {};
  if (typeof value === 'string') {
    const ref = REF.exec(value);
    if (ref) {
      const name = ctx.alive.has(ref[1]) ? ctx.names.get(ref[1]) : undefined;
      if (name !== undefined) return `var(${name})`;
      report(ctx, {
        code: 'reference_target_omitted', severity: 'warning',
        message: `References ${ref[1]}, which this output does not emit; the value was omitted.`,
        details: { target: ref[1], ...member },
      });
      return null;
    }
  }
  switch (type) {
    case 'color': {
      if (typeof value === 'string') return value; // legacy `#rrggbb` or `#rrggbbaa`, verbatim
      const c = asRecord(value);
      if (c && typeof c.hex === 'string' && typeof c.alpha === 'number') {
        if (c.alpha === 1) return c.hex;
        const [r, g, b] = hexChannels(c.hex);
        return `rgb(${r} ${g} ${b} / ${c.alpha})`;
      }
      break;
    }
    case 'dimension':
    case 'duration': {
      if (typeof value === 'string') return value;
      const d = asRecord(value);
      if (d && typeof d.value === 'number' && typeof d.unit === 'string') return `${d.value}${d.unit}`;
      break;
    }
    case 'fontWeight':
      if (typeof value === 'number') return String(value);
      break;
    case 'number':
      if (typeof value === 'number') {
        // CSS reads a bare number as a number, not a length (`height: 36` is
        // dropped). A typography style's `lineHeight` member is the exception:
        // its unit is per style (PIXELS arrives as a `dimension`), so a bare
        // number is a valid CSS multiplier. Every other number, including a
        // top-level LINE_HEIGHT-scoped variable, has no unit because the file
        // states none; it is emitted and reported, never given a unit.
        //
        // Two messages: a token whose scopes state nothing is missing a unit
        // (narrowing scopes is the fix, worded as in the file header); an
        // `OPACITY`/`FONT_WEIGHT` token states it has none, so telling its
        // owner to narrow scopes would be false. Both are reported, since
        // neither is a length.
        if (property !== 'lineHeight') {
          report(ctx, {
            code: 'unitless_number', severity: 'warning',
            message: ctx.statesNumber
              ? 'This token has no unit, because its Figma scopes state it is a unitless number. CSS reads it as a number, not a length, which is what those scopes ask for. Do not use it where a length is expected.'
              : 'This token has no unit, because its Figma variable states none. CSS reads it as a number, not a length. Narrow the variable\'s scopes in Figma and pull again.',
            details: { value, ...member },
          });
        }
        return String(value);
      }
      break;
    case 'cubicBezier':
      if (Array.isArray(value) && value.length === 4 && value.every((n) => typeof n === 'number')) {
        return `cubic-bezier(${value.join(', ')})`;
      }
      break;
    case 'fontFamily':
      if (typeof value === 'string') return quoteFamily(value);
      if (Array.isArray(value) && value.every((f) => typeof f === 'string')) {
        return (value as string[]).map(quoteFamily).join(', ');
      }
      break;
    default:
      break;
  }
  report(ctx, {
    code: 'not_expressible', severity: 'warning',
    message: `CSS has no form for this ${type || 'untyped'} value; it was omitted.`,
    details: { type, value, ...member },
  });
  return null;
}

