// Collection and mode names are free text: a comment terminator in one would
// turn the rest of the name into a live rule, and a line break would split it.
const commentSafe = (text: string): string => text.replace(/\*\//g, '* /').replace(/[\r\n]+/g, ' ');

/**
 * `unitlessCount`: distinct token paths in this file reported `unitless_number`;
 * a file with none keeps the two-line header byte for byte. Each is a token
 * whose Figma variable states no unit (OPACITY and FONT_WEIGHT scopes are
 * excluded upstream), so narrowing scopes is the right remedy for every one.
 * The report path follows the CLI's `outputId` (`packages/cli/src/outputs.ts`)
 * and is stated relative to the pull's output directory, which this layer does
 * not know.
 *
 * `derivedCount`: properties whose unit came from the library's stated usage;
 * naming the unitless ones but not the inferred ones would tell half the truth.
 * The line says "its own Figma variable does not state" because alias-scope
 * evidence is a scope, set on a token that aliases this one.
 */
function headerText(
  header: OutputHeader, nameCase: NameCase, unitlessCount = 0, derivedCount = 0,
): string {
  const lines = [
    `${CSS_HEADER_PREFIX} from library ${commentSafe(header.libraryId)}, foundation ${header.contentHash}, ${header.platform}/${header.format}/${nameCase}.`,
    '   Do not edit. Change the design in Figma, republish, and run spec-layer pull.',
  ];
  if (unitlessCount > 0) {
    const reportFile = `${header.platform}-${header.format}.report.json`;
    if (unitlessCount === 1) {
      lines.push(
        '   1 property in this file has no unit, because its Figma variable states none.',
        `   CSS reads it as a number, not a length. See outputs/${reportFile} under your pull's output directory, or narrow the variable's scopes in Figma.`,
      );
    } else {
      lines.push(
        `   ${unitlessCount} properties in this file have no unit, because their Figma variables state none.`,
        `   CSS reads them as numbers, not lengths. See outputs/${reportFile} under your pull's output directory, or narrow the variables' scopes in Figma.`,
      );
    }
  }
  if (derivedCount > 0) {
    lines.push(
      derivedCount === 1
        ? '   1 property in this file has a unit its own Figma variable does not state, taken from how the library uses the token.'
        : `   ${derivedCount} properties in this file have a unit their own Figma variables do not state, taken from how the library uses those tokens.`,
      `   See tokens/report.json under your pull's output directory for what pinned ${derivedCount === 1 ? 'it' : 'each one'}.`,
    );
  }
  return `${lines.join('\n')} */`;
}

interface Block { selector: string; comment: string; decls: string[] }
interface EmitResult {
  /** One block per DTCG source file that declared anything, in source order. */
  blocks: Map<string, Block>;
  entries: OutputReportEntry[];
  /** Every path (token, shadow, or typography member) that got a declaration this pass. */
  declared: Set<string>;
  /** The DTCG source file that first declared each path, in source order. */
  firstFile: Map<string, string>;
  /** DTCG source file -> token paths reported `unitless_number`, minus those
   *  whose own scopes state a unitless number. */
  unitlessByFile: Map<string, Set<string>>;
  /** DTCG source file -> token paths whose unit was derived from usage. */
  derivedByFile: Map<string, Set<string>>;
}

/** What `cssValue` cannot see: a DTCG leaf carries no scopes, so a `number`
 *  leaf cannot say whether it lacks a unit or states it has none. */
interface PathFacts {
  /** Paths whose Figma scopes state a unitless number (OPACITY, FONT_WEIGHT). */
  statesNumber: Set<string>;
  /** Paths the projection reported `unit_derived_from_usage` for. */
  derived: Set<string>;
}

/** One attempt at every block; a fixed-point retry calls it with a smaller `alive`. */
function emitPass(
  sources: Source[], leavesByFile: Map<string, Leaf[]>, names: Map<string, string>, alive: Set<string>,
  root: string, template: string, modes: Record<string, string> | undefined, facts: PathFacts,
): EmitResult {
  const entries: OutputReportEntry[] = [];
  const declared = new Set<string>();
  const firstFile = new Map<string, string>();
  const blocks = new Map<string, Block>();
  const unitlessByFile = new Map<string, Set<string>>();
  const derivedByFile = new Map<string, Set<string>>();
  const note = (by: Map<string, Set<string>>, file: string, path: string): void => {
    const set = by.get(file) ?? new Set<string>();
    set.add(path);
    by.set(file, set);
  };
  for (const s of sources) {
    const perCollection = modes?.[s.collection];
    const selector = s.isDefault ? root : (perCollection ?? template)
      .replace(/\{mode\}/g, modeSlug(s.file))
      .replace(/\{collection\}/g, collectionSlug(s.file));
    const decls: string[] = [];
    const declaredHere: string[] = [];
    for (const leaf of leavesByFile.get(s.file) ?? []) {
      const ctx: Ctx = {
        names, alive, report: entries, path: leaf.path,
        statesNumber: facts.statesNumber.has(leaf.path),
        ...(s.mode !== null ? { mode: s.mode } : {}),
      };
      if (leaf.type === 'typography') {
        const t = typographyDecls(ctx, leaf, names);
        decls.push(...t.decls);
        for (const p of t.declaredPaths) { declared.add(p); declaredHere.push(p); }
      } else {
        const name = names.get(leaf.path);
        if (name === undefined) continue; // collided; already reported by resolveNames
        if (leaf.type === 'shadow') {
          const d = shadowDecl(ctx, leaf, name);
          if (d !== null) { decls.push(d); declared.add(leaf.path); declaredHere.push(leaf.path); }
        } else {
          const before = entries.length;
          const v = cssValue(ctx, leaf.type, leaf.value);
          if (v !== null) { decls.push(`${name}: ${v};`); declared.add(leaf.path); declaredHere.push(leaf.path); }
          if (entries.length > before && entries[entries.length - 1].code === 'unitless_number'
            && !ctx.statesNumber) {
            note(unitlessByFile, s.file, leaf.path);
          }
          if (v !== null && facts.derived.has(leaf.path)) note(derivedByFile, s.file, leaf.path);
        }
      }
    }
    if (decls.length === 0) continue;
    for (const p of declaredHere) if (!firstFile.has(p)) firstFile.set(p, s.file);
    const comment = `/* ${commentSafe(`${s.collection}${s.mode !== null ? `, ${s.mode}` : ''}`)} */`;
    const existing = blocks.get(s.file);
    if (existing) existing.decls.push(...decls);
    else blocks.set(s.file, { selector, comment, decls });
  }
  return { blocks, entries, declared, firstFile, unitlessByFile, derivedByFile };
}

export function cssOutput(exp: DtcgExport, header: OutputHeader, options: CssOutputOptions = {}): CssOutput {
  const nameCase = options.case ?? CSS_DEFAULTS.case;
  const root = options.root ?? CSS_DEFAULTS.root;
  const template = options.modeSelector ?? CSS_DEFAULTS.modeSelector;
  const sources = sourcesOf(exp.resolver);

  const leavesByFile = new Map<string, Leaf[]>();
  for (const s of sources) {
    if (!leavesByFile.has(s.file)) {
      const out: Leaf[] = [];
      collectLeaves(exp.files[s.file] ?? {}, [], out);
      leavesByFile.set(s.file, out);
    }
  }

  // A typography leaf registers one path per emitted member, never its own (see
  // typographyMemberKeys); a shadow leaf, like a token, registers its path.
  const candidatePaths = new Set<string>();
  for (const leaves of leavesByFile.values()) {
    for (const leaf of leaves) {
      if (leaf.type === 'typography') {
        const value = asRecord(leaf.value) ?? {};
        const ext = leaf.ext ?? {};
        for (const key of typographyMemberKeys(value, ext)) candidatePaths.add(`${leaf.path}.${key}`);
      } else {
        candidatePaths.add(leaf.path);
      }
    }
  }

  const resolved = resolveNames([...candidatePaths], exp.meta, {
    codeSyntaxKey: 'WEB', acceptDeclared: acceptCssDeclared, affix: (body) => `--${body}`, nameCase,
  });
  const names = resolved.names; // permanent: a path missing here collided, and is done

  // What the DTCG leaves cannot state, read from the record that can.
  const facts: PathFacts = {
    statesNumber: new Set(Object.entries(exp.meta)
      .filter(([, entry]) => scopesStateNumber(entry.scopes))
      .map(([path]) => path)),
    derived: new Set(exp.report
      .filter((entry) => entry.code === 'unit_derived_from_usage')
      .map((entry) => entry.path)),
  };
  const emit = (alive: Set<string>) =>
    emitPass(sources, leavesByFile, names, alive, root, template, options.modes, facts);

  // Fixed point on which names a reference may resolve through: a name nothing
  // declares strands whatever references it, so shrink `alive` to what got
  // declared and retry. Each pass attempts every non-collided leaf, so the
  // stable pass carries a complete set of omission reports. Every var() then
  // has a declaration somewhere in the file, though not necessarily in its own
  // block, and a reference across selector blocks is still valid CSS.
  let alive = new Set(names.keys());
  let pass = emit(alive);
  for (;;) {
    if (pass.declared.size === alive.size) break;
    alive = pass.declared;
    pass = emit(alive);
  }

  const fileNames = cssFileNames(sources);
  const map: Record<string, CssMapEntry> = {};
  for (const [path, entry] of Object.entries(resolved.map)) {
    const from = pass.firstFile.get(path);
    if (alive.has(path) && from !== undefined) map[path] = { ...entry, file: fileNames.get(from) as string };
  }

  const entries: OutputReportEntry[] = [...resolved.report, ...pass.entries];

  const shared = [...new Set(sources
    .filter((s) => !s.isDefault && options.modes?.[s.collection] === undefined)
    .map((s) => s.collection))].sort(compareCodeUnits);
  if (shared.length > 1) {
    for (const collection of shared) {
      entries.push({
        code: 'mode_selector_shared', severity: 'warning', path: collection,
        message: `${shared.length} collections with modes share the selector template ${template}; one attribute cannot carry both axes. Declare a selector per collection under outputs[].modes.`,
        details: { modifiers: shared, selector: template },
      });
    }
  }

  const files: Record<string, string> = {};
  const imports: string[] = [];
  for (const [source, block] of pass.blocks) {
    const name = fileNames.get(source) as string;
    const head = headerText(
      header, nameCase,
      pass.unitlessByFile.get(source)?.size ?? 0,
      pass.derivedByFile.get(source)?.size ?? 0,
    );
    files[name] = `${head}\n\n${block.selector} {\n  ${block.comment}\n${block.decls.map((d) => `  ${d}`).join('\n')}\n}\n`;
    imports.push(block.comment, `@import "./${name}";`);
  }
  // index.css only imports, so it never carries the unitless note.
  if (imports.length > 0) files[CSS_INDEX_FILE] = `${headerText(header, nameCase)}\n\n${imports.join('\n')}\n`;
  return { files, map, report: sortReport(entries) };
}
